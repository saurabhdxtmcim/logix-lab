# 3 - Softmax Function
#
# A multiclass neural network generates N outputs. One output is selected as the predicted answer.
# In the output layer, a vector z is generated by a linear function which is fed into a softmax function.
# The softmax function converts z into a probability distribution as described below.
# After applying softmax, each output will be between 0 and 1 and the outputs will sum to 1.
# They can be interpreted as probabilities. The larger inputs to the softmax will correspond to larger output probabilities.
#
# The softmax function can be written:
#
#                exp(z_j)
#     a_j = ---------------------
#           sum_{k=0}^{N-1} exp(z_k)
#
# Where z = w · x + b and N is the number of features/categories in the output layer.
#
# The output of the softmax layer is often interpreted as the probability of each class.
# For example, a_1 = P(y = 1 | x), ..., a_10 = P(y = 10 | x) in the case of 10 output units.

def softmax(z):
    """Softmax function."""
    e_z = np.exp(z - np.max(z))  # subtract max for numerical stability
    return e_z / e_z.sum(axis=0, keepdims=True)

def load_data():
    """
    Loads sample handwritten digit data (like MNIST) and returns (X, y).
    Each row of X is a flattened image, values normalized between 0 and 1.
    y contains the labels.
    """
    try:
        # Try to import keras for MNIST, fallback if not present
        from tensorflow.keras.datasets import mnist
    except ImportError:
        raise ImportError("TensorFlow is required for loading MNIST in this function.")

    # Load MNIST dataset
    (X_train, y_train), (X_test, y_test) = mnist.load_data()
    
    # Flatten images to 1D and normalize
    X_train = X_train.reshape(-1, 28 * 28).astype(np.float32) / 255.0
    X_test = X_test.reshape(-1, 28 * 28).astype(np.float32) / 255.0
    
    # Combine train and test sets (optional)
    X = np.concatenate([X_train, X_test], axis=0)
    y = np.concatenate([y_train, y_test], axis=0)

    return X, y

